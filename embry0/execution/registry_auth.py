"""The orchestrator's login to the image registry (#523).

The in-stack registry refuses anonymous clients. Its login is generated by the
``registry-auth-init`` compose service into a volume, as two files, ``username``
and ``password``; the orchestrator mounts that volume read-only and names it with
``REGISTRY_AUTH_DIR``.

Registry credentials are client-side in Docker: the daemon never stores them. The
docker CLI reads them from its config file and sends them with each pull or push
it asks the daemon to make. So the login goes into the orchestrator's own docker
CLI config, which every ``docker`` command it runs against DinD reads, and DinD
itself needs no change. Nothing here touches the network, so a start never waits
on the registry.
"""

from __future__ import annotations

import base64
import json
import os
import tempfile
from collections.abc import Mapping
from pathlib import Path


class RegistryAuthError(RuntimeError):
    """The registry login is configured but cannot be read or installed."""


def registry_host(image_registry: str) -> str:
    """The host a login is keyed by: ``registry:5000`` -> ``registry:5000``,
    ``ghcr.io/acme`` -> ``ghcr.io``."""
    return image_registry.strip().rstrip("/").split("/", 1)[0]


def read_registry_credential(auth_dir: str | Path) -> tuple[str, str]:
    """``(username, password)`` from ``auth_dir``. RegistryAuthError names the file at fault."""
    values: list[str] = []
    for name in ("username", "password"):
        path = Path(auth_dir) / name
        try:
            value = path.read_text(encoding="utf-8").strip()
        except OSError as exc:
            raise RegistryAuthError(f"cannot read the registry {name} at {path}: {exc}") from exc
        if not value:
            raise RegistryAuthError(f"the registry {name} at {path} is empty")
        values.append(value)
    username, password = values
    if ":" in username:
        raise RegistryAuthError(f"the registry username at {Path(auth_dir) / 'username'} contains ':'")
    return username, password


def docker_config_dir(environ: Mapping[str, str] | None = None) -> Path:
    """Where the docker CLI looks for its config: ``$DOCKER_CONFIG``, else ``~/.docker``."""
    env = os.environ if environ is None else environ
    configured = env.get("DOCKER_CONFIG", "")
    return Path(configured) if configured else Path.home() / ".docker"


def write_docker_login(config_dir: str | Path, host: str, username: str, password: str) -> Path:
    """Set the login for ``host`` in ``config_dir/config.json`` and return that path.

    Other entries in an existing config are kept. The file is replaced atomically,
    mode 0600, inside a 0700 directory.
    """
    if not host:
        raise RegistryAuthError("a registry login needs a registry host")
    directory = Path(config_dir)
    try:
        directory.mkdir(mode=0o700, parents=True, exist_ok=True)
        path = directory / "config.json"
        config: dict[str, object] = {}
        if path.exists():
            loaded = json.loads(path.read_text(encoding="utf-8") or "{}")
            if not isinstance(loaded, dict):
                raise RegistryAuthError(f"{path} is not a JSON object")
            config = loaded
        auths = config.get("auths")
        if not isinstance(auths, dict):
            auths = {}
        token = base64.b64encode(f"{username}:{password}".encode()).decode("ascii")
        auths[host] = {"auth": token}
        config["auths"] = auths
        fd, tmp = tempfile.mkstemp(prefix=".config.", suffix=".json", dir=directory)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                json.dump(config, handle, indent=2)
            os.chmod(tmp, 0o600)
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise
    except (OSError, ValueError) as exc:
        raise RegistryAuthError(f"cannot write the registry login to {directory}: {exc}") from exc
    return path
